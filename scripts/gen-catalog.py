#!/usr/bin/env python3
"""Embeds services/catalog.json into the Swift core as a raw string (SwiftPM resources don't survive .app packaging)."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
data = json.load(open(root / "services/catalog.json"))
text = json.dumps(data, indent=1)
assert '"""#' not in text
out = root / "app/Sources/IMCore/ServiceCatalogData.swift"
out.write_text('// Generated by scripts/gen-catalog.py from services/catalog.json — do not edit.\npublic enum ServiceCatalogData {\n    public static let json = #"""\n' + text + '\n"""#\n}\n')
print("wrote", out, len(data["services"]), "services")
